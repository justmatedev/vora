// Builds two isolated apps from a copy. Production version, identity and feed stay untouched.
import { cp, mkdir, readFile, writeFile, readdir, rm, symlink, chmod } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const platform = process.argv[2] || process.platform;
if (!['linux', 'win32'].includes(platform) || platform !== process.platform)
  throw new Error('Execute nativamente em Linux ou Windows para gerar o respectivo kit.');
const output = join(root, 'release', `update-cycle-${platform}`);
const project = join(output, 'project');
await mkdir(output, { recursive: true });
// This directory is exclusively generated by this script; never remove user profiles.
await rm(project, { recursive: true, force: true });
await mkdir(project);
for (const name of [
  'electron',
  'shared',
  'src',
  'public',
  'assets',
  'scripts',
  'resources/notices',
]) {
  await cp(join(root, name), join(project, name), { recursive: true });
}
for (const name of (await readdir(root)).filter((name) =>
  /^(package(?:-lock)?\.json|tsconfig.*\.json|vite\.config\.ts|index\.html|LICENSE|THIRD_PARTY\.md)$/.test(
    name,
  ),
))
  await cp(join(root, name), join(project, name));
await cp(join(root, 'resources/tools.lock.json'), join(project, 'resources/tools.lock.json'));
const tools = platform === 'linux' ? 'linux-x64' : 'win-x64';
await cp(join(root, 'resources/tools', tools), join(project, 'resources/tools', tools), {
  recursive: true,
});
await symlink(
  join(root, 'node_modules'),
  join(project, 'node_modules'),
  process.platform === 'win32' ? 'junction' : 'dir',
);

async function replace(path, before, after) {
  const content = await readFile(join(project, path), 'utf8');
  if (!content.includes(before)) throw new Error(`Trecho de validação não encontrado: ${path}`);
  await writeFile(join(project, path), content.replace(before, after));
}
await replace(
  'electron/update-adapter.ts',
  "{ provider: 'github' as const, owner: 'justmatedev', repo: 'vora', private: false }",
  "{ provider: 'generic' as const, url: 'http://127.0.0.1:47831/' }",
);
await replace(
  'electron/main.ts',
  "app.setName('Vora');",
  `app.setName('VoraUpdateTest');
// Available only in this generated copy, for reconnecting after a real restart.
if (/^\\d+$/.test(process.env.VORA_CYCLE_DEBUG_PORT || ''))
  app.commandLine.appendSwitch('remote-debugging-port', process.env.VORA_CYCLE_DEBUG_PORT!);`,
);
await replace(
  'electron/main.ts',
  "app.setAppUserModelId('app.vora.desktop')",
  "app.setAppUserModelId('app.vora.update-test')",
);
await replace(
  'electron/main.ts',
  "title: 'Vora',",
  "title: 'VoraUpdateTest — ambiente de validação',",
);
await replace(
  'src/App.tsx',
  '<Logo />',
  '<Logo /><strong style={{color: "#A78BFA", fontSize: 12}}>AMBIENTE DE VALIDAÇÃO</strong>',
);
const pkg = JSON.parse(await readFile(join(project, 'package.json'), 'utf8'));
pkg.name = 'vora-update-test';
pkg.desktopName = 'app.vora.update-test';
pkg.build.appId = 'app.vora.update-test';
pkg.build.productName = 'VoraUpdateTest';
pkg.build.publish = { provider: 'generic', url: 'http://127.0.0.1:47831/' };
pkg.build.linux.executableName = 'vora-update-test';
pkg.build.linux.artifactName = 'VoraUpdateTest-${version}-linux-${arch}.${ext}';
pkg.build.win.executableName = 'VoraUpdateTest';
pkg.build.win.artifactName = 'VoraUpdateTest-${version}-windows-${arch}-setup.${ext}';
pkg.build.nsis = {
  oneClick: false,
  perMachine: false,
  allowElevation: false,
  createDesktopShortcut: false,
  createStartMenuShortcut: true,
};
const lock = JSON.parse(await readFile(join(project, 'package-lock.json'), 'utf8'));
async function version(value) {
  pkg.version = lock.version = lock.packages[''].version = value;
  lock.name = lock.packages[''].name = pkg.name;
  await writeFile(join(project, 'package.json'), JSON.stringify(pkg, null, 2));
  await writeFile(join(project, 'package-lock.json'), JSON.stringify(lock, null, 2));
}
function run(args) {
  return new Promise((accept, reject) => {
    const child = spawn(process.execPath, args, {
      cwd: project,
      stdio: 'inherit',
      env: {
        ...process.env,
        CSC_IDENTITY_AUTO_DISCOVERY: 'false',
      },
    });
    child.on('error', reject);
    child.on('exit', (code) =>
      code === 0 ? accept() : reject(new Error(`Comando falhou (${code}): ${args.join(' ')}`)),
    );
  });
}
await version('0.6.0');
await run([join(root, 'node_modules/typescript/bin/tsc'), '--noEmit']);
await run([join(root, 'node_modules/vite/bin/vite.js'), 'build']);
await run(['scripts/build-electron.mjs']);
await run(['scripts/prepare-notices.mjs']);
await run(['scripts/verify-tools.mjs', platform]);
for (const [label, value] of [
  ['initial', '0.6.0'],
  ['updates', '0.6.1'],
]) {
  await version(value);
  const build = join(output, `${label}-build`);
  await rm(build, { recursive: true, force: true });
  await run([
    join(root, 'node_modules/electron-builder/cli.js'),
    platform === 'linux' ? '--linux' : '--win',
    platform === 'linux' ? 'AppImage' : 'nsis',
    '--x64',
    '--publish',
    'never',
    `--config.directories.output=${build}`,
  ]);
  const target = join(output, label);
  await rm(target, { recursive: true, force: true });
  await mkdir(target);
  for (const name of await readdir(build)) {
    if (/\.(AppImage|exe|blockmap|yml)$/.test(name))
      await cp(join(build, name), join(target, name));
  }
}
await cp(join(root, 'scripts/update-cycle-server.mjs'), join(output, 'serve.mjs'));
await cp(join(root, 'docs/UPDATE-TEST.md'), join(output, 'LEIA-ME.md'));
if (platform === 'linux') {
  await writeFile(
    join(output, 'iniciar-servidor.sh'),
    `#!/bin/sh
set -eu
cd "$(dirname "$0")"
exec env ELECTRON_RUN_AS_NODE=1 APPIMAGE_EXTRACT_AND_RUN=1 ./initial/VoraUpdateTest-0.6.0-linux-x86_64.AppImage ./serve.mjs
`,
  );
  await chmod(join(output, 'iniciar-servidor.sh'), 0o755);
} else {
  // Run the server using a separate runtime copy, so NSIS can replace the installed exe.
  await writeFile(
    join(output, 'iniciar-servidor.cmd'),
    `@echo off\r
cd /d "%~dp0"\r
set "VORA_TEST_DIR=%LOCALAPPDATA%\\Programs\\VoraUpdateTest"\r
if not exist "%VORA_TEST_DIR%\\VoraUpdateTest.exe" set "VORA_TEST_DIR=%LOCALAPPDATA%\\Programs\\vora-update-test"\r
if not "%~1"=="" set "VORA_TEST_DIR=%~1"\r
if not exist "%VORA_TEST_DIR%\\VoraUpdateTest.exe" (echo Informe como argumento a pasta onde VoraUpdateTest foi instalado. & pause & exit /b 1)\r
if not exist ".server-runtime" mkdir ".server-runtime"\r
copy /y "%VORA_TEST_DIR%\\*" ".server-runtime\\" >nul\r
if exist ".server-runtime\\VoraUpdateTest.exe" move /y ".server-runtime\\VoraUpdateTest.exe" ".server-runtime\\VoraUpdateServer.exe" >nul\r
set ELECTRON_RUN_AS_NODE=1\r
".server-runtime\\VoraUpdateServer.exe" "%~dp0serve.mjs"\r
pause\r
`,
  );
}
console.log(`Kit isolado pronto em ${resolve(output)}. Nenhuma Release publicada.`);
